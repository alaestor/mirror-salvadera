function alce.mono.method_getSignature(methodID, optional_methodName) --> dict: of strings{paramtypes, paramnames, returntype, initials, full}
    assert(alce.isPositiveInteger(methodID), 'alce.mono.method_getSignature(): invalid argument: methodID')
    local name = alce.isNonBlankString(optional_methodName) and optional_methodName or mono_method_getName(methodID)
    local paramtypes_raw, paramnames, returntype = mono_method_getSignature(methodID)
    local paramtypes = string.gsub(paramtypes_raw, '/', '+') -- normalize nested typenames to be consistent...
    local t = { types = paramtypes, paramnames = paramnames, returntype = returntype }
    t.initials = string.format('%s(%s)', name, paramtypes or '')
    local typenames=mono_splitParameters(paramtypes)
    local params = ''
    if typenames and #typenames == #paramnames then
        local rr={}
        for i=1, #typenames do rr[i] = typenames[i] .. ' ' .. paramnames[i] end
        params = table.concat(rr, ",")
    end
    local front = string.gsub(string.match(mono_method_getFullName(methodID), "^(.-) %("), '/', '+') -- chop off params and normalize
    t.full = string.format('%s(%s)', front, params)
    return t
end

function alce.mono.class_getParentHierarchy(classID) --> array of class IDs ordered from parent to child (with classID being last)
    assert(alce.isPositiveInteger(classID), 'alce.mono.class_getParentHierarchy(): invalid argument: classID: ' .. tostring(classid))
    local hierarchy = {}
    local current_class = classID
    while current_class and current_class ~= 0 do
        table.insert(hierarchy, 1, current_class)
        current_class = mono_class_getParent(current_class)
    end
    return hierarchy
end

--[[{
    Returns type-categorized value and metadata subtables keyed by field name.

    - `static` a dict of name-keyed static addresses.

    - `offset` dict of name-keyed integer offsets.

    - `const` dict of name-keyed static-const value literals (such as enum values or other constants)

    - `constToKey` dict that's the inverse mapping of const: value to key (useful for quick string lookups)

    Also defines `startOffset` to be the lowest offset; either the result of `mono_structfields_getStartOffset(fields)` or `0x10` (64bit) / `0x8` (32bit) depending on target architecture. Note that this may not be the start of the object if parent's aren't included.

    If `optional_keepMetadata` is true, then the subtable `meta` will contain subtables `const`, `static`, and `offset`
    each of which are dicts with keys identical to the main tables, each of which will contain contain
    `typename`, `type`, `vtype`, `monotype`, and `flags` for their respective counterpart. e.g.
    `class.meta.offset.hp` holds the metadata for `class.offset.hp`. One thing to note is that `vtype` is the result of
    `monoTypeToVartypeLookup[monotype]` so it may be nil.

    If `optional_keepFields` is true, then the subtable `fields` will contain a reference to the raw enumerated fields.

    In cases of collision, the derived class field 'shadows' (overwrites) the base class field.
    To access a shadowed field, you'll need to get the fields of the parent separately.
    Collisions probably shouldn't occur unless `optional_getParents` is `true`.

    *Note: automatically removes `enumSeperator` and `enumSeparatorCharArray` from `const` value list*
--}]]
function alce.mono.getProcessedFields(classID, optional_getParents, optional_hierarchy, optional_keepMetadata, optional_keepFields) --> nil|dict: { static, const, offset, meta? = { const, static, offset }, fields? }
    local fields = mono_class_enumFields(classID, optional_getParents)
    if type(fields) ~= 'table' then
        alce.warn('alce.mono.getProcessedFields(): failed to lookup fields')
        return nil
    end
    if optional_getParents == true then
        assert(optional_hierarchy == nil or alce.isNonEmptyTable(optional_hierarchy), 'alce.mono.getProcessedFields(): Invalid argument: optional_hierarchy')
        fields = alce.mono.sortByHierarchy(fields, optional_hierarchy or alce.mono.class_getParentHierarchy(classID))
    end
    local startOffset = mono_structfields_getStartOffset(fields)
    if not startOffset then startOffset = targetIs64Bit() and 0x10 or 0x8 end
    local t = {
        startOffset = startOffset,
        const = {},
        static = {},
        offset = {},
        meta = optional_keepMetadata == true and {
            const = {},
            static = {},
            offset = {},
        } or nil,
        constToKey = {},
        fields = optional_keepFields == true and fields or nil,
    }
    local function warnIfCollides(subtable, f)
        if not t[subtable][f.name] then return nil end
        local dstr = ((not alce.cfg.debug_print and "Set 'alce.cfg.debug_print=true` for more information.")
            or string.format('\n[WARN-DEBUG]>\nReplacing...\n---\n%s\n---\nwith data from...\n---\n%s\n---\n',
                alce.fmt.table(t[subtable][f.name]), alce.fmt.table(f)))
        alce.debug(string.format("alce.mono.getProcessedFields(): duplicate %s field named '%s' detected. %s", subtable, f.name, dstr))
    end
    local function store(ts, f, val)
        warnIfCollides(ts, f)
        t[ts][f.name] = val
        if optional_keepMetadata == true then
            t.meta[ts][f.name] = {}
            local meta = t.meta[ts][f.name]
            for _,k in pairs({ 'typename', 'type', 'monotype', 'flags' }) do meta[k] = f[k] end
            meta.vtype = monoTypeToVartypeLookup[meta.monotype] or nil
        end
    end
    for _,f in pairs(fields) do
        if f.staticAddress then store('static', f, f.staticAddress)
        elseif f.isConst then store('const', f, mono_class_getStaticFieldValue(classID, f.field))
        elseif f.offset then store('offset', f, f.offset)
        else alce.warn("alce.mono.getProcessedFields(): uncategorized field; what is this?\n??:" .. alce.fmt.table(f)) end
    end
    -- get rid of some junk
    t.const.enumSeperator = nil
    t.static.enumSeparatorCharArray = nil
    if next(t.const) then for k,v in pairs(t.const) do t.constToKey[v] = k end end
    return t or nil
end

--[[{
    Returns a table of methods keyed by the function name (e.g. `SetHealth`) or initials (e.g. `SetHealth(single)`).
    Overloaded methods will have no short "name" key, and must be disambiguated by initials (which includes the parameter types).

    In cases of collision, the derived class method 'shadows' (overwrites) the base class method.
    To access a shadowed method, you'll need to get the methods of the parent separately.
--}]]
function alce.mono.getProcessedMethods(classID, optional_getParents, optional_hierarchy) --> nil|dict: { key = alce.mono.Method, ... }
    local methods = mono_class_enumMethods(classID, optional_getParents)
    if type(methods) ~= 'table'  then
        alce.warn('alce.mono.getProcessedMethods(): Failed to enumerate methods')
        return nil
    end
    if optional_getParents == true then -- ensures we overwrite the right methods...
        assert(optional_hierarchy == nil or alce.isNonEmptyTable(optional_hierarchy), 'alce.mono.getProcessedMethods(): Invalid argument: optional_hierarchy')
        methods = alce.mono.sortByHierarchy(methods, optional_hierarchy or alce.mono.class_getParentHierarchy(classID))
    end
    local t={}
    for _,mpack in ipairs(methods) do
        local m = alce.mono.Method:new(mpack.method, mpack.name, mpack.flags)
        -- tombstone the shorthand if method is overloaded, but not if it's free or merely shadowing.
        if not t[mpack.name] or (t[m.signature.initials] and t[mpack.name] ~= 'tombstone') then t[mpack.name] = m
        else t[mpack.name] = 'tombstone' end
        t[m.signature.initials] = m
    end
    for k,_ in pairs(t) do if t[k] == 'tombstone' then t[k] = nil end end
    return t
end


