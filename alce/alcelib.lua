--- returns whether CE is attached to a valid process
function alce.isAttached()
    return process and readInteger(process) ~= 0
end

function alce.isInteger(value)
    return type(value) == 'number' and math.type(value) == 'integer'
end

function alce.isPositiveInteger(value)
    return type(value) == 'number' and math.type(value) == 'integer' and value > 0
end

function alce.isNonNegativeInteger(value)
    return type(value) == 'number' and math.type(value) == 'integer' and value >= 0
end

function alce.isFloat(value)
    return type(value) == 'number' and math.type(value) == 'float'
end

function alce.isNonNegativeFloat(value)
    return type(value) == 'number' and math.type(value) == 'float' and value >= 0.0
end

function alce.isFiniteNumber(value)
    return type(value) == 'number' and value == value and value ~= math.huge and value ~= -math.huge
end

function alce.isNonEmptyString(value)
    return type(value) == 'string' and value ~= ''
end

function alce.isNonBlankString(value)
    return type(value) == 'string' and string.find(value, '%S') ~= nil
end

function alce.isEmptyTable(value)
    return type(value) == 'table' and next(value) == nil
end

function alce.isNonEmptyTable(value)
    return type(value) == 'table' and next(value) ~= nil
end

function alce.isZeroEmptyOrNil(value)
    local t = type(value)
    return t == nil or (t == 'number' and value == 0) or alce.isEmptyTable(value) or (not alce.isNonBlankString(value))
end

function alce.isCallable(value)
    if type(value) == 'function' then return true end
    local mt = getmetatable(value)
    return mt ~= nil and type(mt.__call) == 'function'
end

function alce.isBetween(value, minimum, maximmum)
    return value > minimum and value < maximum
end

--- checks that the vlaue `isInteger` and within positive and negative `optional_tooFarBoundary` (or `alce.cfg.isOffset_tooFarBoundary`)
function alce.isSignedOffsetlike(value, optional_tooFarBoundary)
    local boundary = (optional_tooFarBoundary or alce.cfg.isOffset_tooFarBoundary)
    return alce.isInteger(value) and value > -boundary and value < boundary
end

--- checks that the value `isNonNegativeInteger` and less than `optional_tooFarBoundary` (or `alce.cfg.isOffset_tooFarBoundary`)
function alce.isOffsetlike(value, optional_tooFarBoundary)
    return alce.isNonNegativeInteger(value) and value < (optional_tooFarBoundary or alce.cfg.isOffset_tooFarBoundary)
end

--- checks that the value `isInteger` and greater than `optional_nearNullBoundary` (or `alce.cfg.isAddress_nearNullBoundary`) and less than `optional_userspaceBoundary` (or `alce.cfg.isAddress_userspaceBoundary`)
function alce.isAddresslike(value, optional_nearNullBoundary, optional_userspaceBoundary)
    return alce.isInteger(value) and  value > (optional_nearNullBoundary or alce.cfg.isAddress_nearNullBoundary) and value < (optional_userspaceBoundary or (targetIs64Bit() and alce.cfg.isAddress_userspaceBoundary64 or alce.cfg.isAddress_userspaceBoundary32))
end

function alce.hasFlag(flag, flags) --> boolean: equivalent  `(flags & flag) == flag`
    return (flags & flag) == flag
end

--- passthru assert with source line (checks positive, e.g. `assert(value)` or `assert(optional_checker(value))`)
function alce.check(value, optional_checker) --> the input value
    local info = debug.getinfo(2, "Sl")
    assert(optional_checker == nil or alce.isCallable(optional_checker), 'line ' .. tostring(info.currentline) .. ': alce.check: invalid argument: optional_checker not callable.')
    assert(optional_checker and optional_checker(value) or value, 'line ' .. tostring(info.currentline) .. ': alce.check( ' .. tostring(value) .. ' )')
    return value
end

--- passthru negation-assert with source line (checks negative, e.g. `assert(not value)` or `assert(not optional_checker(value))`)
function alce.ncheck(value, optional_checker) --> the input value
    local info = debug.getinfo(2, "Sl")
    assert(optional_checker == nil or alce.isCallable(optional_checker), 'line ' .. tostring(info.currentline) .. ': alce.check: invalid argument: optional_checker not callable.')
    assert(not (optional_checker and optional_checker(value) or value), 'line ' .. tostring(info.currentline) .. ': alce.ncheck( ' .. tostring(value) .. ' )')
    return value
end

--- Traverses a pointer chain by repeating safe readPointer calls: (pointer, offsets,...)
function alce.readPointerChain(pointer, ...) --> nil|address
    assert(alce.isAddresslike(pointer), 'alce.readPointerChain(): invalid argument: pointer')
    local currentPtr = readPointer(pointer)
    local offsets = {...}
    for _,offset in ipairs(offsets) do
        if not alce.isOffsetlike(offset) then alce.warn('alce.readPointerChain(): suspicious offset: ' .. tostring(offset)) end
        currentPtr = readPointer(currentPtr + offset)
        if not alce.isAddresslike(currentPtr) then
            alce.warn('alce.readPointerChain(): invalid address when trying to chain the following:\n' .. alce.fmt.table({pointer=pointer, offsets=offsets}))
            return nil
        end
    end
    return currentPtr
end

--- just readPointerChain but it asserts the resulting address isAddressLike
function alce.safeChain(pointer, ...) --> address
    local info = debug.getinfo(2, "Sl")
    local result = alce.readPointerChain(pointer, ...)
    assert(alce.isAddresslike(result), 'line ' .. tostring(info.currentline) .. ': alce.safeChain(): resulting pointer was invalid:\n' .. alce.fmt.table({pointer=pointer, offsets=offsets, result=result}))
    return result
end

function alce.enumerate(iterator, optional_startFrom) --> integer from optional_startFrom or 1 , result of `iterator()`
    assert(alce.isCallable(iterator), 'alce.enumerate(): invalid argument: iterator: ' .. tostring(iterator))
    assert(optional_startFrom == nil or type(optional_startFrom) == 'number', 'alce.enumerate(): invalid argument: optional_startFrom' .. (optional_startFrom))
    local count = optional_startFrom or 1
    return function()
        local value = iterator()
        if value == nil then return nil end
        count = count + 1
        return count-1, value
    end
end

--- Recursively nil's keys with empty tables
function alce.prune(tbl)
    if type(tbl) ~= "table" then return end
    for k, v in pairs(tbl) do
        if type(v) == "table" then
            alce.prune(v)
            if next(v) == nil then tbl[k] = nil end
        end
    end
end

function alce.keyFromValue(value, tbl) --> nil or the first key associated with a given value
    for k,v in pairs(tbl) do if v == value then return k end end
end

function alce.keysFromValue(value, tbl) --> nil or an array of all the keys associated with a given value
    local keys={}
    for k,v in pairs(tbl) do if v == value then table.insert(keys, k) end end
    table.sort(keys)
    return next(keys) and keys or nil
end

--- assigns k,v pairs `from`->`to`, silently overwriting any duplicate keys
function alce.unsafeExtend(to, from)
    for k,v in pairs(from) do to[k] = v end
end

--- assigns k,v pairs `from`->`to`, asserting that the `from` key doesn't already exist in `to`
function alce.extend(to, from)
    for k,v in pairs(from) do
        assert(not to[k], 'alce.safeExtend(): key already exists: ' .. tostring(k))
        to[k] = v
    end
end
