alce.fmt = {}

function alce.fmt.titleCase(str) --> string: "title case" -> "Title Case"
    return str:gsub("(%a)([%w']*)", function(first, rest) return first:upper() .. rest:lower() end)
end

local function byte_to_bits(byte)
    local bits = {}
    for i = 7, 0, -1 do bits[#bits + 1] = (byte >> i) & 1 end
    return table.concat(bits)
end
function alce.fmt.binary(value, optional_useDouble, optional_useNativeEndian) --> string: `0b` prefixed big-endien binary string representation in groups of 8
    assert(type(value) == 'number', 'alce.fmt.binary(): expected number, got type: ' .. type(value))
    local endian = optional_useNativeEndian and '' or '>'
    local fmt = (math.type(value) == 'integer') and (endian .. 'j') or (endian .. (optional_useDouble and 'd' or 'f'))
    local bytes = string.pack(fmt, value)
    local t = {}
    for i = 1, #bytes do t[i] = byte_to_bits(string.byte(bytes, i)) end
    return '0b' .. table.concat(t, ' ')
end

local BYTE_TO_HEX = {}
for i = 0, 255 do BYTE_TO_HEX[i] = string.format("%02X", i) end
function alce.fmt.hex(value, optional_withPadding, optional_useNativeEndian) --> string: 0x prefixed hexadecimal string representation
    assert(type(value) == 'number', 'alce.fmt.hex(): expected number, got type: ' .. type(value))
    local endian = optional_useNativeEndian and '' or '>'
    local fmt = (math.type(value) == 'integer') and (endian .. 'j') or (endian .. 'd')
    local bytes = string.pack(fmt, value)
    local hex = {}
    for i = 1, #bytes do hex[i] = BYTE_TO_HEX[string.byte(bytes, i)] end
    local result = table.concat(hex)
    if optional_withPadding ~= true then
        result = result:gsub("^0+", "")
        if result == "" then result = "0" end
    end
    return '0x' .. result
end

function alce.fmt.address(value) --> `alce.fmt.hex(value, true, false)` padded to address length
    if not alce.isInteger(value) then return 'NaN: ' .. tostring(value) end
    local full = alce.fmt.hex(value, true, false)
    if targetIs64Bit() then return full
    else return '0x' .. full:sub(-8) end
end

function alce.fmt.sanitizeSymbolName(str) --> string: the input string with non-alphanumeric replaced with underscores
    return string.gsub(str, '[^%a%d]', '_')
end

function alce.fmt.pretty(value, optional_printFullTable) --> string: single line, unless value is a table and optional_printFullTable is true.
    local t = type(value)
    if t == 'table' and optional_printFullTable then return alce.fmt.table(value)
    elseif t == 'string' then return '"' .. value .. '"'
    elseif t == 'number' then return string.format('%s  (%s: %s)', tostring(value), math.type(value), alce.fmt.hex(value))
    elseif t == 'function' or t == 'thread' or t == 'userdata' then return '<' .. tostring(value) .. '>'
    else return tostring(value) end
end

function alce.fmt.table(tbl, optional_depthLimit, optional_keysToIgnore, optional_dontToString, optional_dontSortKeys, internal_depth, internal_seen, internal_path) --> string: the human-readable representation of the table
    local depth = internal_depth or 0
    local seen = internal_seen or {}
    local path = internal_path or "root"
    local keysToIgnore = optional_keysToIgnore or {}
    local dontToString = optional_dontToString == true
    if type(tbl) ~= "table" or optional_depthLimit == depth then return alce.fmt.pretty(tbl) end
    if seen[tbl] then return string.format("<circular reference to %s @ %s>", seen[tbl], tostring(tbl):gsub("table: ", "")) end
    seen[tbl] = path
    if not dontToString then
        local mt = getmetatable(tbl)
        if mt and type(mt.__tostring) == "function" then
            local ok, str = pcall(mt.__tostring, tbl)
            if ok then return str end
        end
    end
    local result = {}
    local prefix = string.rep("  ", depth)
    -- Collect keys, skipping ignored ones
    local keys = {}
    for k in pairs(tbl) do if not keysToIgnore[k] then table.insert(keys, k) end end
    -- Sort unless disabled
    if not dontSortKeys then
        table.sort(keys, function(a, b)
            local ta, tb = type(a), type(b)
            if ta == tb then return a < b end
            return ta < tb
        end)
    end
    for _, k in ipairs(keys) do
        local v = tbl[k]
        local key_str = (type(k) == "string") and k or "[" .. tostring(k) .. "]"
        local current_path = path .. "." .. key_str
        local line_prefix = prefix .. key_str .. " = "
        if type(v) ~= "table" then table.insert(result, line_prefix .. alce.fmt.pretty(v))
        else
            if seen[v] then table.insert(result, line_prefix .. string.format("<circular reference to %s @ %s>", seen[v], tostring(v):gsub("table: ", "")))
            elseif next(v) == nil then table.insert(result, line_prefix .. "{}")
            else
                table.insert(result, line_prefix .. "{")
                table.insert(result, alce.fmt.table(v, optional_depthLimit, keysToIgnore, dontSortKeys, useCustomToString, depth + 1, seen, current_path))
                table.insert(result, prefix .. "}")
            end
        end
    end
    return table.concat(result, "\n")
end
