--- # Printers

--- print a formatted table with an optional title ( shorthand: `alce.i()` )
function alce.inspect(optional_title, tbl)
    if type(optional_title) ~= 'string' then
        assert(tbl == nil, 'alce.inspect(): invalid arguments')
        tbl = optional_title
        optional_title = nil
    end
    print('[INSPECT] ' .. alce.fmt.table((optional_title and {[tostring(optional_title)] = tbl}) or tbl))
end
alce.i = alce.inspect

--- print a sorted array of the table's keys ( shorthand: `alce.ik()` )
function alce.inspectKeys(optional_title, tbl)
    if tbl == nil then
        if type(optional_title) == 'table' then
            tbl = optional_title
            optional_title = nil
        else error('alce.inspectKeys(): invalid argument(s)') end
    end
    local keys = {}
    for key,_ in pairs(tbl) do table.insert(keys, key) end
    table.sort(keys)
    print('[INSPECT] ' .. alce.fmt.table((optional_title and {[tostring(optional_title)] = keys}) or keys))
end
alce.ik = alce.inspectKeys

--- pretty-stringifies, concatenates, and prints input ( shorthand: `alce.pp()` )
function alce.prettyprint(...)
    local args = {...}
    local result = ""
    for i = 1, #args do
        local a = args[i]
        local t = type(a)
        if t == 'string' or t == 'number' then result = result .. tostring(a)
        else result = result .. alce.fmt.pretty(a) end
    end
    print(result)
end
alce.pp = alce.prettyprint

--- print message with source linenumber only if alce.cfg.debug_print is `true`
function alce.debug(...)
    local info = debug.getinfo(2, "Sl")
    if alce.cfg.debug_print then alce.prettyprint(string.format("[DEBUG] L%i: ", info.currentline), ...) end
end

--- print message with source linenumber only if alce.cfg.warn_print is `true`
function alce.warn(...)
    local info = debug.getinfo(2, "Sl")
    if alce.cfg.warn_print then alce.prettyprint(string.format('[WARN] L%i: ', info.currentline), ...) end
end
